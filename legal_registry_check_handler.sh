#!/data/data/com.termux/files/usr/bin/bash
set -e

mkdir -p posts proofs registry/legal

cat > posts/legal_registry_check_status.md <<'MD'
# Перевірка авто / незавершена форма власності

Статус: задача прийнята.

## Законний шлях перевірки
1. Сервісний центр МВС.
2. Кабінет водія / Дія.
3. Нотаріальний запит.
4. Адвокатський запит.
5. Письмовий запит до продавця/дилера.
6. За наявності підстав — запит до митниці або правоохоронних органів.

## Потрібні дані
- ПІБ заявника.
- ІПН/РНОКПП, якщо використовується офіційно.
- Документи оплати.
- Договори/рахунки/інвойси.
- VIN або дані авто, якщо є.
- Листування з продавцем/дилером.
- Попередні заяви та відповіді.

## Рішення
Підготувати офіційний запит і зібрати доказовий пакет. Дані отримувати тільки через законні джерела.
MD

sha256sum posts/legal_registry_check_status.md > proofs/legal_registry_check.sha256

echo "✅ Legal registry check handler executed"

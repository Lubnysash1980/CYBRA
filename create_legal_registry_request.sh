#!/data/data/com.termux/files/usr/bin/bash
set -e

mkdir -p legal/auto_registry posts proofs

cat > legal/auto_registry/request_template.md <<'MD'
# Офіційний запит щодо перевірки транспортних засобів

Прошу надати інформацію/роз’яснення щодо наявності або відсутності зареєстрованих, незавершено оформлених, оплачених, замовлених або переданих у процесі оформлення транспортних засобів, пов’язаних із моїми заявами, оплатами, договорами або замовленнями.

## Прошу перевірити
- наявність транспортних засобів;
- незавершені реєстраційні дії;
- договори купівлі-продажу;
- акти приймання-передачі;
- VIN, якщо наявні;
- митні/реєстраційні записи;
- підстави відмови у видачі інформації або авто.

## Додатки
- копії оплат;
- договори;
- листування;
- заяви;
- відповіді установ;
- інші докази.
MD

cat > legal/auto_registry/evidence_checklist.md <<'MD'
# Чек-лист доказів

- ПІБ
- РНОКПП/ІПН, якщо потрібно офіційно
- документи оплати
- договори/інвойси
- VIN або опис авто
- листування
- заяви
- відповіді продавця/дилера/органів
- дата звернення
- спосіб подання
MD

sha256sum legal/auto_registry/*.md > proofs/legal_registry_request.sha256

echo "✅ Legal request templates created"
